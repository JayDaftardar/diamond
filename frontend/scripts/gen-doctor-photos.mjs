// Lists the image files in public/images/doctors and writes src/content/doctor-photos.ts.
// Runs before dev and build (see package.json) so the site only shows photos that exist,
// and the admin panel can offer exactly these file names.
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'public/images/doctors')
const files = existsSync(dir)
  ? readdirSync(dir)
      .filter((f) => /^[a-z0-9-]+\.(webp|jpe?g|png)$/.test(f))
      .sort()
  : []

const out = `// GENERATED by scripts/gen-doctor-photos.mjs. Do not edit by hand.
// Photo files available in public/images/doctors.
export const DOCTOR_PHOTOS: readonly string[] = ${JSON.stringify(files, null, 2)}
`
writeFileSync(join(root, 'src/content/doctor-photos.ts'), out)
console.log(`doctor-photos: ${files.length} file(s)`)
